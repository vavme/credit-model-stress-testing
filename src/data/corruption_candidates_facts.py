"""Clean-state facts behind the corruption candidate proposal (EDA session, Section 8).

Reads data/processed/train.csv ONLY. Writes reports/eda/section8_facts.md. Nothing is
corrupted here. The label-flip table is arithmetic on the clean counts, not a simulation.
No models are trained. Candidates are a proposal: picking them is tracker item 1.7 (Vav).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from src.data.eda import DAYS_EMPLOYED_SENTINEL

ROOT = Path(__file__).resolve().parents[2]
TRAIN_PATH = ROOT / "data" / "processed" / "train.csv"
OUT_PATH = ROOT / "reports" / "eda" / "section8_facts.md"
SEVERITIES = (0.0, 0.10, 0.25, 0.50)


def label_flip_table(n_rows: int, n_pos: int, severities=SEVERITIES) -> pd.DataFrame:
    """Expected counts if a share of true defaults is recorded as 0 (late defaults not yet seen). Pure arithmetic."""
    rows = []
    for s in severities:
        pos = n_pos * (1 - s)
        rows.append({"severity": s, "positives": pos, "default_rate_pct": pos / n_rows * 100,
                     "positives_in_1pct_bin": pos * 0.01, "ratio_0_to_1": (n_rows - pos) / pos})
    return pd.DataFrame(rows)


def decile_rates(x: pd.Series, y: np.ndarray, k: int = 10) -> pd.DataFrame:
    q = pd.qcut(x, k, duplicates="drop")
    g = pd.DataFrame({"q": q, "y": y}).groupby("q", observed=True)["y"].agg(["size", "mean"])
    g["mean"] *= 100
    return g


def main() -> None:
    df = pd.read_csv(TRAIN_PATH)
    n = len(df)
    y = df["TARGET"].to_numpy()
    out = ["# Section 8 facts (train split only)", "",
           "Generated by `src/data/corruption_candidates_facts.py`. Clean-state numbers only. Nothing is corrupted and no model is trained.", ""]

    # ---- A1: EXT_SOURCE_2
    ext = df[["EXT_SOURCE_1", "EXT_SOURCE_2", "EXT_SOURCE_3", "DAYS_BIRTH"]]
    c = ext.corr()
    s = df["EXT_SOURCE_2"]
    out += ["## EXT_SOURCE_2 (Scenario A candidate)", "",
            f"- Missing: {int(s.isna().sum()):,} rows ({s.isna().mean():.2%}). Quantiles p1 / p25 / p50 / p75 / p99: " + " / ".join(f"{s.quantile(q):.3f}" for q in (.01, .25, .5, .75, .99)) + ".",
            f"- Pearson r with EXT_SOURCE_1: {c.loc['EXT_SOURCE_2', 'EXT_SOURCE_1']:+.3f}; with EXT_SOURCE_3: {c.loc['EXT_SOURCE_2', 'EXT_SOURCE_3']:+.3f}; with DAYS_BIRTH: {c.loc['EXT_SOURCE_2', 'DAYS_BIRTH']:+.3f}. (EXT_1 vs EXT_3: {c.loc['EXT_SOURCE_1', 'EXT_SOURCE_3']:+.3f}.) Low r means the other two scores cannot stand in for it.",
            f"- Spearman with TARGET: {spearmanr(s.dropna(), y[s.notna().to_numpy()]).statistic:+.3f}. Default rate by decile (low to high score): " + ", ".join(f"{v:.1f}%" for v in decile_rates(s.dropna(), y[s.notna().to_numpy()])["mean"]) + ".",
            f"- Rows with all three EXT scores present: {int(ext[['EXT_SOURCE_1', 'EXT_SOURCE_2', 'EXT_SOURCE_3']].notna().all(axis=1).sum()):,} ({ext[['EXT_SOURCE_1', 'EXT_SOURCE_2', 'EXT_SOURCE_3']].notna().all(axis=1).mean():.2%}); with none present: {int(ext[['EXT_SOURCE_1', 'EXT_SOURCE_2', 'EXT_SOURCE_3']].isna().all(axis=1).sum()):,}.", ""]

    # ---- A2: AMT_INCOME_TOTAL
    inc = df["AMT_INCOME_TOTAL"]
    rho = spearmanr(inc, y).statistic
    dr = decile_rates(inc, y)
    out += ["## AMT_INCOME_TOTAL (Scenario A candidate, low signal)", "",
            f"- Missing: {int(inc.isna().sum())} rows. Quantiles p1 / p25 / p50 / p75 / p99 / max: " + " / ".join(f"{inc.quantile(q):,.0f}" for q in (.01, .25, .5, .75, .99)) + f" / {inc.max():,.0f}.",
            f"- Spearman with TARGET: {rho:+.3f}. Decile default rates: " + ", ".join(f"{v:.1f}%" for v in dr["mean"]) + f" (range {dr['mean'].max() - dr['mean'].min():.2f} pp).",
            f"- Spearman with AMT_CREDIT: {spearmanr(inc, df['AMT_CREDIT']).statistic:+.3f}; with AMT_ANNUITY: {spearmanr(inc, df['AMT_ANNUITY'].fillna(df['AMT_ANNUITY'].median())).statistic:+.3f}; with EXT_SOURCE_2 (non-missing): {df['AMT_INCOME_TOTAL'].corr(df['EXT_SOURCE_2'], method='spearman'):+.3f}.",
            f"- By NAME_INCOME_TYPE, median income: " + "; ".join(f"{k} {v:,.0f}" for k, v in df.groupby('NAME_INCOME_TYPE')['AMT_INCOME_TOTAL'].median().items() if df['NAME_INCOME_TYPE'].eq(k).sum() > 1000) + ".", ""]

    # ---- B: labels
    npos = int(y.sum())
    t = label_flip_table(n, npos)
    out += ["## TARGET labels (Scenario B candidate)", "",
            f"- Clean train: {n:,} rows, {npos:,} defaults ({npos / n:.2%}).",
            "- If a share of true defaults is recorded as 0 (late defaults not yet seen), expected counts by severity (arithmetic, not simulated):", "",
            "| Share of defaults hidden | Defaults left | Default rate | Defaults in a 1% bin | Ratio 0 : 1 |", "|---|---|---|---|---|"]
    out += [f"| {r.severity:.0%} | {r.positives:,.0f} | {r.default_rate_pct:.2f}% | {r.positives_in_1pct_bin:,.0f} | {r.ratio_0_to_1:.1f} : 1 |" for r in t.itertuples()]
    out += ["", f"- Contrast: flipping that same share of 0s to 1 instead would add up to 10% x {n - npos:,} = {0.10 * (n - npos):,.0f} false defaults at severity 10%, so 'hide defaults' and 'add false defaults' change the class ratio very differently.", ""]

    # ---- C1: amounts
    cr, an = df["AMT_CREDIT"], df["AMT_ANNUITY"]
    ok = an.notna()
    term = (cr[ok] / an[ok])
    pti = an[ok] / df.loc[ok, "AMT_INCOME_TOTAL"]
    out += ["## AMT_CREDIT and AMT_ANNUITY (Scenario C candidate: scale or unit drift)", "",
            f"- Medians: AMT_CREDIT {cr.median():,.0f}; AMT_ANNUITY {an.median():,.0f}. Pearson r between them: {cr.corr(an):+.3f}.",
            f"- Decile default rates AMT_CREDIT: " + ", ".join(f"{v:.1f}%" for v in decile_rates(cr, y)['mean']) + ".",
            f"- Decile default rates AMT_ANNUITY: " + ", ".join(f"{v:.1f}%" for v in decile_rates(an[ok], y[ok.to_numpy()])['mean']) + ".",
            f"- Implied term (AMT_CREDIT / AMT_ANNUITY, hypothesis for 'number of instalments'): p10 / p50 / p90 = " + " / ".join(f"{term.quantile(q):.1f}" for q in (.1, .5, .9)) + ". Unchanged if both columns are scaled by the same factor.",
            f"- Payment-to-income (AMT_ANNUITY / AMT_INCOME_TOTAL): p10 / p50 / p90 = " + " / ".join(f"{pti.quantile(q):.3f}" for q in (.1, .5, .9)) + ". Changes if only the amounts are scaled and income is not.",
            f"- Spearman with TARGET: implied term {spearmanr(term, y[ok.to_numpy()]).statistic:+.3f}; payment-to-income {spearmanr(pti, y[ok.to_numpy()]).statistic:+.3f}.", ""]

    # ---- C2: DAYS_EMPLOYED
    de = df["DAYS_EMPLOYED"]
    sent = de == DAYS_EMPLOYED_SENTINEL
    last = de[~sent]
    recent = (last > -333) & (last <= 0)
    inc_type = df["NAME_INCOME_TYPE"]
    out += ["## DAYS_EMPLOYED placeholder (Scenario C candidate: schema or sentinel change)", "",
            f"- Placeholder {DAYS_EMPLOYED_SENTINEL}: {int(sent.sum()):,} rows ({sent.mean():.2%}), default rate {y[sent.to_numpy()].mean():.2%}. Other rows: {y[~sent.to_numpy()].mean():.2%}.",
            f"- Placeholder rows that are Pensioner or Unemployed: {int(inc_type[sent].isin(['Pensioner', 'Unemployed']).sum()):,} of {int(sent.sum()):,}. Pensioner or Unemployed rows that are NOT placeholder: {int((inc_type.isin(['Pensioner', 'Unemployed']) & ~sent).sum())}. So NAME_INCOME_TYPE carries almost the same fact.",
            f"- Shortest real tenures (DAYS_EMPLOYED between -333 and 0, n={int(recent.sum()):,}): default rate {y[(~sent).to_numpy()][recent.to_numpy()].mean():.2%}. Value 0 would land in this group if the placeholder were recoded to 0.",
            f"- Pensioners: default rate {y[(inc_type == 'Pensioner').to_numpy()].mean():.2%} (n={int((inc_type == 'Pensioner').sum()):,}).", ""]

    # ---- bureau block as control
    b = df["AMT_REQ_CREDIT_BUREAU_YEAR"]
    out += ["## Low-signal control (not a candidate): bureau enquiry block", "",
            f"- 6 columns, {b.isna().mean():.2%} natural missing (informative: +2.84 pp, Section 5). Best single-column decile range 1.68 pp (QRT), YEAR 1.35 pp.", ""]

    OUT_PATH.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
