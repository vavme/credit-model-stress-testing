"""Phase 1 integrity check and split-index record (EDA session, Section 1).

What it does:
  1. Structural checks on the full raw file: shape, duplicate rows, duplicate
     SK_ID_CURR, TARGET is binary with no missing values. These need the whole
     file because a duplicate that straddles two splits would be leakage. No
     distributions or feature-target statistics are computed on the full file.
  2. Re-derives the one locked 60/20/20 split with split.make_split (seed 42) and
     saves its row positions to data/interim/split_indices.csv. It does NOT open
     data/processed/test.csv or val.csv. It confirms the re-derived train split
     matches data/processed/train.csv by SK_ID_CURR.
  3. Dtypes, memory and constant columns are computed on the train split only.

The raw file is opened read-only. Writes go to data/interim/ and reports/eda/.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import pandas as pd

from src.data.split import RAW_PATH, SEED, make_split

ROOT = Path(__file__).resolve().parents[2]
TRAIN_PATH = ROOT / "data" / "processed" / "train.csv"
INTERIM_DIR = ROOT / "data" / "interim"
REPORT_DIR = ROOT / "reports" / "eda"
INDICES_PATH = INTERIM_DIR / "split_indices.csv"
REPORT_PATH = REPORT_DIR / "section1_integrity.md"


def check_raw(df: pd.DataFrame) -> dict:
    """Structural checks only. Pure."""
    target = df["TARGET"]
    return {
        "rows": len(df),
        "cols": df.shape[1],
        "duplicate_rows": int(df.duplicated().sum()),
        "duplicate_ids": int(df["SK_ID_CURR"].duplicated().sum()),
        "target_missing": int(target.isna().sum()),
        "target_values": sorted(target.dropna().unique().tolist()),
    }


def split_indices(df: pd.DataFrame, seed: int = SEED) -> pd.DataFrame:
    """Row position in the raw file, SK_ID_CURR and split label for every row."""
    train_df, val_df, test_df = make_split(df, seed=seed)
    parts = [("train", train_df), ("val", val_df), ("test", test_df)]
    out = pd.concat(
        [
            pd.DataFrame(
                {
                    "raw_row": part.index.to_numpy(),
                    "SK_ID_CURR": part["SK_ID_CURR"].to_numpy(),
                    "split": name,
                }
            )
            for name, part in parts
        ],
        ignore_index=True,
    )
    return out.sort_values("raw_row").reset_index(drop=True)


def constant_columns(df: pd.DataFrame) -> list[str]:
    """Columns with at most one distinct non-missing value."""
    return [c for c in df.columns if df[c].nunique(dropna=True) <= 1]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def run() -> None:
    raw_hash_before = sha256(RAW_PATH)
    raw = pd.read_csv(RAW_PATH)
    raw_checks = check_raw(raw)

    idx = split_indices(raw)
    train_df, val_df, test_df = make_split(raw)

    # Confirm the re-derived train split is the file on disk. Only train.csv is read.
    disk_train_ids = pd.read_csv(TRAIN_PATH, usecols=["SK_ID_CURR"])["SK_ID_CURR"]
    train_matches_disk = set(disk_train_ids) == set(train_df["SK_ID_CURR"]) and len(
        disk_train_ids
    ) == len(train_df)

    INTERIM_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    idx.to_csv(INDICES_PATH, index=False)

    # ---- everything below is train only ----
    const = constant_columns(train_df)
    dtype_counts = train_df.dtypes.astype(str).value_counts()
    mem_mb = train_df.memory_usage(deep=True).sum() / 1e6

    total = len(raw)
    lines = [
        "# Section 1: data integrity and split",
        "",
        f"Generated by `src/data/integrity.py`. Seed: {SEED}.",
        "",
        "## Raw file structural checks (full file, no distributions)",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Rows x columns | {raw_checks['rows']:,} x {raw_checks['cols']} |",
        f"| Duplicate rows | {raw_checks['duplicate_rows']:,} |",
        f"| Duplicate SK_ID_CURR | {raw_checks['duplicate_ids']:,} |",
        f"| TARGET missing | {raw_checks['target_missing']:,} |",
        f"| TARGET distinct values | {raw_checks['target_values']} |",
        f"| Raw file sha256 unchanged by this run | {raw_hash_before == sha256(RAW_PATH)} |",
        f"| Raw sha256 | `{raw_hash_before}` |",
        "",
        "## Split (stratified on TARGET)",
        "",
        "| Split | Rows | Share | Positives | TARGET rate |",
        "|---|---|---|---|---|",
    ]
    for name, part in [("train", train_df), ("val", val_df), ("test", test_df)]:
        lines.append(
            f"| {name} | {len(part):,} | {len(part) / total:.2%} | "
            f"{int(part['TARGET'].sum()):,} | {part['TARGET'].mean():.4%} |"
        )
    lines += [
        "",
        f"- Re-derived train split equals `data/processed/train.csv` (same SK_ID_CURR set and size): {train_matches_disk}.",
        "- `val.csv` and `test.csv` were not opened. Their sizes and TARGET rates above come from re-running the seeded split in memory.",
        f"- Indices saved to `{INDICES_PATH.relative_to(ROOT).as_posix()}` ({len(idx):,} rows: raw_row, SK_ID_CURR, split).",
        "",
        "## Train split only: shape, dtypes, memory, constant columns",
        "",
        f"- Shape: {train_df.shape[0]:,} x {train_df.shape[1]}",
        f"- Dtypes: {', '.join(f'{k}: {v}' for k, v in dtype_counts.items())}",
        f"- Memory (deep): {mem_mb:,.1f} MB",
        f"- Constant columns (<= 1 distinct non-missing value): {const if const else 'none'}",
    ]
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    run()
