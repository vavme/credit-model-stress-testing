"""Target and class imbalance on the train split (EDA session, Section 4).

Reads data/processed/train.csv ONLY. Writes reports/eda/section4_target.md.
No models are trained. The "scores" used to illustrate metrics are a constant
and a seeded random number, so the metric values show what a useless score gets.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import ks_2samp
from sklearn.metrics import average_precision_score, roc_auc_score

SEED = 42
ROOT = Path(__file__).resolve().parents[2]
TRAIN_PATH = ROOT / "data" / "processed" / "train.csv"
OUT_PATH = ROOT / "reports" / "eda" / "section4_target.md"


def imbalance_stats(y: pd.Series) -> dict:
    """Counts, rate, ratio and the metrics of an 'always predict 0' rule. Pure."""
    n = len(y)
    pos = int(y.sum())
    neg = n - pos
    return {
        "n": n,
        "pos": pos,
        "neg": neg,
        "rate": pos / n,
        "ratio": neg / pos,
        "acc_all_zero": neg / n,
        "recall_all_zero": 0.0,
    }


def useless_score_metrics(y: pd.Series, seed: int = SEED) -> dict:
    """AUC, PR-AUC and KS of a constant score and of a random score. Pure given the seed."""
    rng = np.random.default_rng(seed)
    rand = rng.random(len(y))
    const = np.zeros(len(y))
    return {
        "auc_const": roc_auc_score(y, const),
        "ap_const": average_precision_score(y, const),
        "auc_rand": roc_auc_score(y, rand),
        "ap_rand": average_precision_score(y, rand),
        "ks_rand": ks_2samp(rand[y.to_numpy() == 1], rand[y.to_numpy() == 0]).statistic,
    }


def main() -> None:
    y = pd.read_csv(TRAIN_PATH, usecols=["TARGET"])["TARGET"]
    s = imbalance_stats(y)
    m = useless_score_metrics(y)
    flip10 = s["pos"] + 0.10 * s["neg"]
    lines = [
        "# Section 4: target and class imbalance (train split only)",
        "",
        "Generated by `src/data/target_balance.py`. Labels: [DATA] verified by code, [GENERAL] domain knowledge, hypotheses marked.",
        "",
        "## The numbers [DATA]",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Rows | {s['n']:,} |",
        f"| TARGET = 1 (default) | {s['pos']:,} ({s['rate']:.2%}) |",
        f"| TARGET = 0 | {s['neg']:,} ({1 - s['rate']:.2%}) |",
        f"| Imbalance ratio (0 : 1) | {s['ratio']:.2f} : 1, about 1 default per {s['ratio'] + 1:.1f} applications |",
        "",
        "## Why accuracy is misleading",
        "",
        "Accuracy is the share of rows predicted correctly. A rule that approves everyone and predicts 'no default' for all rows:",
        "",
        "| Metric | 'Always predict 0' |",
        "|---|---|",
        f"| Accuracy | {s['acc_all_zero']:.2%} |",
        f"| Recall on defaults (share of defaulters caught) | {s['recall_all_zero']:.0%} (0 of {s['pos']:,}) |",
        "",
        f"So a model must beat {s['acc_all_zero']:.2%} accuracy just to match a rule that finds no defaulter. Accuracy also depends on a cutoff, and a scorecard is used at many cutoffs.",
        "",
        "## The metrics used instead (plain words)",
        "",
        "- **AUC (ROC AUC):** pick one defaulter and one non-defaulter at random. AUC is the chance the model gives the defaulter the higher risk score. 0.5 is a coin flip, 1.0 is perfect. It does not depend on a cutoff and it ignores the class ratio.",
        "- **Gini:** 2 x AUC - 1. Same information on a 0 to 1 scale. Banks quote it.",
        "- **KS (Kolmogorov-Smirnov):** the largest gap between the share of defaulters and the share of non-defaulters scored below the same cutoff. Banks use it as 'the best separation point'. 0 is none, 1 is perfect.",
        "- **PR-AUC (average precision):** area under the precision-recall curve. Precision is the share of flagged applicants who default. Unlike AUC, it moves when the class ratio moves. A useless score gets about the default rate, not 0.5.",
        "",
        "What a useless score gets on this train split (a constant, and a seeded random number):",
        "",
        "| Score | AUC | PR-AUC | KS |",
        "|---|---|---|---|",
        f"| Constant (no ranking) | {m['auc_const']:.3f} | {m['ap_const']:.4f} | 0 |",
        f"| Random, seed {SEED} | {m['auc_rand']:.3f} | {m['ap_rand']:.4f} | {m['ks_rand']:.4f} |",
        "",
        f"Read the PR-AUC row against the default rate of {s['rate']:.4f}: that is the floor. A PR-AUC of 0.20 on this data is therefore a 2.5x gain, even though 0.20 looks small.",
        "",
        "## What imbalance means for this project",
        "",
        "- **Splits:** stratified on TARGET, which is already done. The rate is 8.07% in train, val and test. [DATA, Section 1]",
        f"- **Bin stability (WOE / scorecard):** with {s['pos']:,} defaults in train, a bin holding 1% of rows has about {round(s['pos'] * 0.01):,} defaults if it follows the base rate. Bins from rare categories can have a handful. This will matter when you pick bins in a later phase. [DATA arithmetic]",
        f"- **Confidence intervals:** the project's 'worth it' rule uses a bootstrap interval on the complexity premium (GBM minus baseline). With about 4,965 defaults each in val and test (from the Section 1 split), intervals on small differences will not be tight, and the width is not measured yet. Hypothesis, to be checked when the bootstrap exists.",
        f"- **Label noise (Scenario B):** if 10% of the 0 labels were flipped to 1, the positive count would rise from {s['pos']:,} to about {flip10:,.0f} and the default rate to about {flip10 / s['n']:.1%}. The class ratio moves as well as the label quality, and that should be a deliberate choice when the corruption is designed. Arithmetic only, nothing implemented.",
        "- **Do not rebalance (hypothesis for a later phase):** oversampling or class weights change probabilities and are not needed to rank. A bank scorecard needs calibrated PD, so the project should say how it handles that. This is a question for Vav, not a decision.",
        "",
        "## Minor note",
        "",
        f"The rate 8.07% is for this sample. A bank's real portfolio rate depends on the definition of TARGET (X and Y are not given) and on who was approved. [GENERAL]",
    ]
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
